import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('prepared Supabase schema: RLS, roles, atomic RPC rules, capacity and single use', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create schema auth; create table auth.users(id uuid primary key); create role anon; create role authenticated;
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      grant usage on schema auth to anon,authenticated; grant execute on function auth.uid() to anon,authenticated;
      create publication supabase_realtime;`);
    await db.exec(await readFile(new URL('../supabase/schema.sql',import.meta.url),'utf8'));
    const owner='00000000-0000-4000-8000-000000000001', a='00000000-0000-4000-8000-000000000002', b='00000000-0000-4000-8000-000000000003';
    for(const id of [owner,a,b]) await db.query('insert into auth.users(id) values($1)',[id]);
    const asUser=async(id,role='authenticated')=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);await db.exec(`set role ${role}`);};
    await asUser(owner);
    const created=(await db.query("select public.cevai_create_pub('Pub de teste','Cidade Baixa','Endereço de teste','Ambiente de teste',-30.04,-51.21) as result")).rows[0].result;
    assert.ok(created.pub?.id); const pub=created.pub.id;
    const createdOther=(await db.query("select public.cevai_create_pub('Outro pub','Bom Fim','Outro endereço','Ambiente de teste',-30.02,-51.21) as result")).rows[0].result;
    const otherPub=createdOther.pub.id;
    const offer=(await db.query(`insert into public.cevai_offers(pub_id,title,subtitle,description,category,rule,days,start_time,end_time,daily_limit) values($1,'Uma boa oferta','Chopp Pilsen em dobro','Descrição de teste','Chopp em dobro','Validar antes do pedido',array[0,1,2,3,4,5,6],'00:00','23:59',1) returning id`,[pub])).rows[0].id;
    await asUser(a);
    assert.equal((await db.query('select * from public.cevai_staff')).rows.length,0);
    await assert.rejects(db.query("insert into public.cevai_offers(pub_id,title) values($1,'Não permitido')",[pub]));
    const first=(await db.query('select public.cevai_activate($1) as result',[offer])).rows[0].result.redemption;
    assert.ok(first?.token); assert.match(first.code,/^CEV-[A-HJ-NP-Z2-9]{4}$/);
    const same=(await db.query('select public.cevai_activate($1) as result',[offer])).rows[0].result.redemption;
    assert.equal(same.id,first.id);
    await assert.rejects(db.query("update public.cevai_redemptions set status='redeemed' where id=$1",[first.id]));
    await asUser(b);
    assert.equal((await db.query('select * from public.cevai_redemptions')).rows.length,0);
    const soldOut=(await db.query('select public.cevai_activate($1) as result',[offer])).rows[0].result;
    assert.match(soldOut.error,/esgotaram/);
    await assert.rejects(db.query('select public.cevai_redeem($1,$2)',[pub,first.code]));
    await asUser(owner);
    const wrongPub=(await db.query('select public.cevai_redeem($1,$2) as result',[otherPub,first.code])).rows[0].result;
    assert.match(wrongPub.error,/não encontrado/);
    const redeemed=(await db.query('select public.cevai_redeem($1,$2) as result',[pub,'cevai:'+first.token])).rows[0].result;
    assert.equal(redeemed.redemption.status,'redeemed');
    const duplicate=(await db.query('select public.cevai_redeem($1,$2) as result',[pub,first.code])).rows[0].result;
    assert.match(duplicate.error,/já utilizado/);
    const offer2=(await db.query(`insert into public.cevai_offers(pub_id,title,subtitle,description,category,rule,days,start_time,end_time,daily_limit) values($1,'Outra oferta','Petisco em promoção','Descrição de teste','Petiscos','Validar antes do pedido',array[0,1,2,3,4,5,6],'00:00','23:59',1) returning id`,[pub])).rows[0].id;
    await asUser(a);
    const cancelled=(await db.query('select public.cevai_activate($1) as result',[offer2])).rows[0].result.redemption;
    await db.query('select public.cevai_cancel($1)',[cancelled.id]);
    await asUser(b);
    const expires=(await db.query('select public.cevai_activate($1) as result',[offer2])).rows[0].result.redemption;
    assert.ok(expires.id);
    await db.exec('reset role');
    await db.query("update public.cevai_redemptions set created_at=now()-interval '20 minutes',expires_at=now()-interval '1 minute' where id=$1",[expires.id]);
    await asUser(owner);
    const expired=(await db.query('select public.cevai_redeem($1,$2) as result',[pub,expires.code])).rows[0].result;
    assert.match(expired.error,/expirou/);
    await asUser(a);
    const released=(await db.query('select public.cevai_activate($1) as result',[offer2])).rows[0].result;
    assert.ok(released.redemption.id);
    await asUser('', 'anon');
    assert.equal((await db.query('select * from public.cevai_redemptions')).rows.length,0);
    await assert.rejects(db.query('select public.cevai_activate($1)',[offer]));
    assert.equal((await db.query('select * from public.cevai_pubs')).rows.length,2);
  } finally { await db.close(); }
});
